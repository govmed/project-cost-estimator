function Invoke-Init {
    param([string]$TargetPath)

    $resolved = (Resolve-Path -Path (Split-Path -Parent $TargetPath) -ErrorAction SilentlyContinue)
    if (-not (Test-Path $TargetPath)) {
        New-Item -ItemType Directory -Path $TargetPath -Force | Out-Null
    }
    $absTarget = (Resolve-Path $TargetPath).Path

    Write-Log "Initializing SOW Calculator project at: $absTarget"

    $createdDirs = 0
    foreach ($d in $Directories) {
        $full = Join-Path $TargetPath $d
        if (New-DirIfMissing -Path $full) {
            $createdDirs++
            Write-Log "created dir: $d" "new"
        }
    }

    $createdFiles = 0
    foreach ($key in $PlaceholderFiles.Keys) {
        $full = Join-Path $TargetPath $key
        if (Write-FileIfAbsent -Path $full -Content $PlaceholderFiles[$key]) {
            $createdFiles++
            Write-Log "created file: $key" "new"
        }
    }

    $state = [ordered]@{
        version         = $ManifestVersion
        initialized_at  = (Get-Date).ToUniversalTime().ToString("o")
        target          = $absTarget
        directories     = $Directories
    }
    $statePath = Join-Path $TargetPath ".sync/state.json"
    Write-Utf8NoBom -Path $statePath -Content ($state | ConvertTo-Json -Depth 4)

    Write-Log "done. $createdDirs dirs and $createdFiles files created." "ok"
    Write-Log "next: paste files from Claude into docs/ and src/, or run with -Manifest." "info"
    return 0
}

function Invoke-ApplyManifest {
    param([string]$TargetPath, [string]$ManifestPath)

    if (-not (Test-Path $ManifestPath)) {
        Write-Log "manifest not found: $ManifestPath" "err"
        return 1
    }

    try {
        $manifest = Get-Content -Path $ManifestPath -Raw | ConvertFrom-Json
    } catch {
        Write-Log "manifest is not valid JSON: $_" "err"
        return 1
    }

    if ($manifest.version -ne $ManifestVersion) {
        Write-Log "manifest version mismatch (expected $ManifestVersion, got $($manifest.version))" "warn"
    }

    if (-not $manifest.files) {
        Write-Log "manifest has no 'files' array" "err"
        return 1
    }

    $label = if ($manifest.label) { $manifest.label } else { "(unlabeled)" }
    Write-Log "applying manifest: $label — $($manifest.files.Count) files"

    $new = 0; $updated = 0; $skipped = 0
    foreach ($entry in $manifest.files) {
        if (-not $entry.path) {
            Write-Log "entry missing 'path'" "warn"
            continue
        }
        $rel = $entry.path
        $content = if ($null -ne $entry.content) { $entry.content } else { "" }
        $mode = if ($entry.mode) { $entry.mode } else { "overwrite" }

        $out = Join-Path $TargetPath $rel
        $parent = Split-Path -Parent $out
        if ($parent -and -not (Test-Path $parent)) {
            New-Item -ItemType Directory -Path $parent -Force | Out-Null
        }

        $existed = Test-Path $out -PathType Leaf
        if ($existed -and $mode -eq "skip-if-exists") {
            $skipped++
            Write-Log "skip (exists): $rel" "info"
            continue
        }

        Write-Utf8NoBom -Path $out -Content $content
        if ($existed) {
            $updated++
            Write-Log "updated: $rel" "ok"
        } else {
            $new++
            Write-Log "wrote:   $rel" "new"
        }
    }

    $applied = [ordered]@{
        applied_at       = (Get-Date).ToUniversalTime().ToString("o")
        manifest_label   = $manifest.label
        manifest_sha256  = Get-FileSha256 -Path $ManifestPath
        counts           = [ordered]@{ new = $new; updated = $updated; skipped = $skipped }
    }
    $appliedPath = Join-Path $TargetPath ".sync/last-applied.json"
    Write-Utf8NoBom -Path $appliedPath -Content ($applied | ConvertTo-Json -Depth 4)

    Write-Log "done. $new new, $updated updated, $skipped skipped." "ok"
    return 0
}

function Invoke-Verify {
    param([string]$TargetPath)

    if (-not (Test-Path $TargetPath)) {
        Write-Log "target does not exist: $TargetPath" "err"
        return 1
    }
    $abs = (Resolve-Path $TargetPath).Path
    Write-Log "verifying structure at: $abs"

    $missingDirs = @()
    foreach ($d in $Directories) {
        if (-not (Test-Path -Path (Join-Path $TargetPath $d) -PathType Container)) {
            $missingDirs += $d
        }
    }
    $missingFiles = @()
    foreach ($f in $PlaceholderFiles.Keys) {
        if (-not (Test-Path -Path (Join-Path $TargetPath $f) -PathType Leaf)) {
            $missingFiles += $f
        }
    }

    if ($missingDirs.Count -eq 0 -and $missingFiles.Count -eq 0) {
        Write-Log "structure intact." "ok"
        return 0
    }

    foreach ($d in $missingDirs) { Write-Log "missing dir: $d" "warn" }
    foreach ($f in $missingFiles) { Write-Log "missing file: $f" "warn" }
    Write-Log "run without -Verify to repair." "info"
    return 1
}

# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

if ($Verify) {
    exit (Invoke-Verify -TargetPath $Target)
}

$rc = Invoke-Init -TargetPath $Target
if ($rc -ne 0) { exit $rc }

if ($Manifest) {
    $rc = Invoke-ApplyManifest -TargetPath $Target -ManifestPath $Manifest
}

exit $rc
