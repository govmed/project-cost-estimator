<#
.SYNOPSIS
    SOW Cost Calculator — Local Environment Bootstrap (PowerShell).

.DESCRIPTION
    Creates the project directory tree and optionally applies a sync manifest
    produced by Claude in a conversation. Idempotent: safe to re-run.

    Equivalent in behavior to scripts/bootstrap.py.

.PARAMETER Target
    Target directory. Default: ./sow-calculator

.PARAMETER Manifest
    Path to a sync manifest JSON to apply after init.

.PARAMETER Verify
    Check structure without modifying anything.

.EXAMPLE
    .\bootstrap.ps1
    .\bootstrap.ps1 -Target .\sow-calc
    .\bootstrap.ps1 -Manifest .\sync-manifest.json
    .\bootstrap.ps1 -Verify

.NOTES
    Requires PowerShell 5.1+ (Windows PowerShell) or PowerShell 7+ (cross-platform).
#>

[CmdletBinding()]
param(
    [string]$Target = "./sow-calculator",
    [string]$Manifest,
    [switch]$Verify
)

$ErrorActionPreference = "Stop"

# ---------------------------------------------------------------------------
# Project structure — keep in sync with bootstrap.py
# ---------------------------------------------------------------------------

$ManifestVersion = "1.0"

$Directories = @(
    "docs",
    "docs/decisions",
    "docs/wireframes",
    "src",
    "src/engine",
    "src/engine/calculations",
    "src/data",
    "src/types",
    "src/ui",
    "src/ui/components",
    "src/ui/pages",
    "seed",
    "seed/rate-cards",
    "seed/cloud-pricing",
    "seed/scenarios",
    "scripts",
    "tests",
    "tests/engine",
    "tests/fixtures",
    ".sync"
)

$PlaceholderFiles = [ordered]@{
    "README.md" = "# SOW Cost Calculator`n`nGenerated by bootstrap.ps1. See docs/ for design deliverables.`n"
    "docs/00-prompt.md" = "<!-- Place the original SOW_Cost_Calculator_Prompt.md here. -->`n"
    "docs/01-clarifying-questions.md" = "<!-- Deliverable #1 -->`n"
    "docs/02-information-architecture.md" = "<!-- Deliverable #2 -->`n"
    "docs/03-data-model.md" = "<!-- Deliverable #3 -->`n"
    "docs/04-calculation-logic.md" = "<!-- Deliverable #4 -->`n"
    "docs/05-wireframes.md" = "<!-- Deliverable #5 -->`n"
    "docs/06-seed-data.md" = "<!-- Deliverable #6 -->`n"
    "docs/07-tech-stack.md" = "<!-- Deliverable #7 -->`n"
    "docs/08-phase1-build-plan.md" = "<!-- Deliverable #8 -->`n"
    "docs/09-risks-and-defensibility.md" = "<!-- Deliverable #9 -->`n"
    ".gitignore" = "node_modules/`ndist/`nbuild/`n.env`n.env.local`n*.log`n.DS_Store`n.sync/last-applied.json`n"
    ".sync/README.md" = "# Sync directory`n`nManaged by scripts/bootstrap.ps1. Tracks which manifest from Claude was last applied so we can diff state between conversations.`n"
}

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

function Write-Log {
    param(
        [string]$Message,
        [ValidateSet("info", "ok", "warn", "err", "new")]
        [string]$Level = "info"
    )
    $icon = switch ($Level) {
        "ok"   { "[OK] " }
        "warn" { "[!]  " }
        "err"  { "[X]  " }
        "new"  { "[+]  " }
        default { "     " }
    }
    $color = switch ($Level) {
        "ok"   { "Green" }
        "warn" { "Yellow" }
        "err"  { "Red" }
        "new"  { "Cyan" }
        default { "Gray" }
    }
    Write-Host "$icon$Message" -ForegroundColor $color
}

function Get-FileSha256 {
    param([string]$Path)
    return (Get-FileHash -Path $Path -Algorithm SHA256).Hash.ToLower()
}

# Reusable, single source of truth: writes UTF-8 *without* BOM.
# PowerShell 5.1's `Set-Content -Encoding UTF8` writes a BOM, which breaks
# package.json, tsconfig.json, postcss.config.js, and any other file that
# `JSON.parse` or a JS parser tries to read directly.
function Write-Utf8NoBom {
    param([string]$Path, [string]$Content)
    $utf8NoBom = New-Object System.Text.UTF8Encoding $false
    [System.IO.File]::WriteAllText($Path, $Content, $utf8NoBom)
}

function New-DirIfMissing {
    param([string]$Path)
    if (Test-Path -Path $Path -PathType Container) {
        return $false
    }
    New-Item -ItemType Directory -Path $Path -Force | Out-Null
    return $true
}

function Write-FileIfAbsent {
    param([string]$Path, [string]$Content)
    if (Test-Path -Path $Path -PathType Leaf) {
        return $false
    }
    $parent = Split-Path -Parent $Path
    if ($parent -and -not (Test-Path $parent)) {
        New-Item -ItemType Directory -Path $parent -Force | Out-Null
    }
    Write-Utf8NoBom -Path $Path -Content $Content
    return $true
}

